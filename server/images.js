// Image generation — one swappable seam, mirrors how brain.js wraps the text
// model. Every renderer is a "provider" behind the same interface, so new ones
// (local Stable Diffusion, a paid API, a better card engine) drop in WITHOUT
// touching the screen or the routes. The UI just lists whatever is available.
//
// Providers shipped today:
//   - cards        : branded Larkwell graphic cards, generated as SVG. FULLY LOCAL,
//                    no key, nothing leaves the machine. This is the default.
//   - pollinations : free online photo/abstract generation, no API key. Only a
//                    short text prompt leaves the machine (the post is public).
// Future slots, already wired (light up when their env var is set):
//   - local-sd     : a local Stable Diffusion / AUTOMATIC1111 endpoint (SD_WEBUI_URL).
//   - openai       : OpenAI gpt-image-1 (OPENAI_API_KEY).
//
// Generated bytes are always saved locally under data/images/ and served from
// /api/images/file/<name>, so an image is yours on disk the moment it exists.

