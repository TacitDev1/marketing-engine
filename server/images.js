// Turn a LinkedIn post (or any text) into image direction: a punchy card
// headline + subline, and a vivid text-to-image prompt for photo providers.
// Falls back to a naive extraction if the model is unavailable.
export async function buildImageDirection({ text }) {
  const src = String(text || "").trim().slice(0, 1500);
  const fallback = () => {
    const firstLine = src.split("\n").find((l) => l.trim()) || company.name;
    return {
      headline: firstLine.replace(/[#*]/g, "").trim().split(/(?<=[.!?])\s/)[0].slice(0, 70),
      subline: company.oneLiner ? String(company.oneLiner).slice(0, 60) : "",
      visualPrompt: `Professional, modern enterprise technology scene representing SAP and cloud transformation, clean composition, corporate blue palette, no text, no logos, high detail, photographic.`,
    };
  };
  if (!src) return fallback();
  const FORMAT = {
    type: "object",
    properties: {
      headline: { type: "string" },
      subline: { type: "string" },
      visualPrompt: { type: "string" },
    },
    required: ["headline", "subline", "visualPrompt"],
  };
  const messages = [
    {
      role: "system",
      content: [
        `You turn a LinkedIn post into image direction for ${company.name}, ${company.oneLiner}`,
        `Return JSON only:`,
        `- "headline": a punchy on-image card headline, MAX 7 words, no hashtags, no emoji, title-case-ish.`,
        `- "subline": a short supporting line, 3 to 7 words.`,
        `- "visualPrompt": a vivid text-to-image prompt for a PHOTO/illustration that fits the post. Describe a concrete scene. Corporate, modern, enterprise SAP/cloud aesthetic, blue palette. NO text in the image, NO logos, NO watermarks. One or two sentences.`,
      ].join("\n"),
    },
    { role: "user", content: `POST:\n${src}\n\nReturn the image direction as JSON.` },
  ];
  try {
    const out = await chatJSON(messages, FORMAT, { numPredict: 320 });
    const fb = fallback();
    return {
      headline: (out.headline || fb.headline).replace(/[#*"]/g, "").trim().slice(0, 80),
      subline: (out.subline || "").replace(/[#*"]/g, "").trim().slice(0, 80),
      visualPrompt: (out.visualPrompt || fb.visualPrompt).trim().slice(0, 800),
    };
  } catch {
    return fallback();
  }
}

// ---------- generate ----------

export async function generateImage({ providerId, prompt, headline, subline, style, size, draftId, nowISO }) {
  const provider = providerById(providerId) || providerById("cards");
  if (!provider.available()) {
    const err = new Error(`Provider "${provider.id}" is not configured.`);
    err.code = "provider_unavailable";
    throw err;
  }
  const now = Date.parse(nowISO) || 0;
  const id = newId(now);
  const { bytes, ext, mime, sourceUrl, credit, unsplashId } = await provider.render({ prompt, headline, subline, style, size });

  if (!fs.existsSync(FILES_DIR)) fs.mkdirSync(FILES_DIR, { recursive: true });
  const file = `${id}.${ext}`;
  fs.writeFileSync(path.join(FILES_DIR, file), bytes);

  const record = {
    id,
    provider: provider.id,
    kind: provider.kind,
    local: provider.local,
    file,
    url: `/api/images/file/${file}`,
    mime,
    size: size || "linkedin",
    style: provider.kind === "card" ? style || "brand" : null,
    headline: headline || null,
    subline: subline || null,
    prompt: prompt || null,
    sourceUrl: sourceUrl || null,
    credit: credit || null, // e.g. "Photo by X on Unsplash" — shown in the gallery, paste it with the post
    unsplashId: unsplashId || null, // dedupe: this photo won't be served again while the record exists
    draftId: draftId || null,
    createdAt: nowISO,
  };
  const list = load();
  list.push(record);
  persist(list);
  return record;
}

// Find ffmpeg without depending on the brain's PATH (it's a user-space static
// binary in ~/.local/bin; PATH isn't guaranteed when launched from Claude).
const FFMPEG_CANDIDATES = () => {
  const home = process.env.HOME || os.homedir();
  return [process.env.FFMPEG_PATH, path.join(home, ".local", "bin", "ffmpeg"), "/usr/bin/ffmpeg", "/usr/local/bin/ffmpeg"].filter(Boolean);
};
function resolveFfmpeg() {
  for (const c of FFMPEG_CANDIDATES()) {
    try { if (fs.existsSync(c)) return c; } catch { /* keep looking */ }
  }
  return "ffmpeg"; // last resort: hope it's on PATH
}

// Is ffmpeg actually there? Prod ran for two weeks with every GIF export failing
// as "spawn ffmpeg ENOENT" and the UI saying only "Export failed" (handoff
// 2026-09-23). Checked once at boot (logged) and exposed on /api/health so the
// export buttons can say so before anyone clicks them.
export function ffmpegStatus() {
  const resolved = resolveFfmpeg();
  let available = false;
  if (path.isAbsolute(resolved)) {
    available = fs.existsSync(resolved);
  } else {
    // Bare "ffmpeg": look along PATH.
    available = (process.env.PATH || "").split(path.delimiter).some((dir) => dir && fs.existsSync(path.join(dir, resolved)));
  }
  return {
    available,
    path: available ? resolved : null,
    hint: available ? null : `ffmpeg not found (checked ${FFMPEG_CANDIDATES().join(", ")} and PATH); animated exports will fail. Install it (Ubuntu: sudo apt install ffmpeg) or set FFMPEG_PATH in .env.`,
  };
}

// ---------- assemble a deterministic frame sequence into a seamless loop ----------
// The browser renders EXACTLY one full rotation of the ASCII art as PNG frames
// (phase 0→1, whole turns, so frame N would equal frame 0). We encode frames
// 0..N-1 at a constant frame rate, so the loop is perfect — no wall-clock jitter,
// no capture compression. Highest quality possible, and it loops cleanly.
// ONE ffmpeg at a time, and never forever: on a shared instance two exports at
// once pinned every CPU, and a hung encode kept running until restart. Jobs
// queue behind each other; anything over FFMPEG_TIMEOUT_MS is killed.
const FFMPEG_TIMEOUT_MS = Number(process.env.FFMPEG_TIMEOUT_MS) || 4 * 60000;
let ffmpegQueue = Promise.resolve();
function runFfmpeg(ff, args) {
  const job = () =>
    new Promise((resolve, reject) => {
      const proc = spawn(ff, args);
      let err = "";
      let timedOut = false;
      const timer = setTimeout(() => {
        timedOut = true;
        try { proc.kill("SIGKILL"); } catch { /* already gone */ }
      }, FFMPEG_TIMEOUT_MS);
      proc.stderr.on("data", (d) => { err += d.toString(); });
      proc.on("error", (e) => { clearTimeout(timer); reject(new Error(`ffmpeg failed to start (${ff}): ${e.message}`)); });
      proc.on("close", (code) => {
        clearTimeout(timer);
        if (timedOut) return reject(new Error(`ffmpeg killed after ${Math.round(FFMPEG_TIMEOUT_MS / 60000)} min (too long)`));
        code === 0 ? resolve() : reject(new Error(`ffmpeg exited ${code}: ${err.slice(-500)}`));
      });
    });
  const p = ffmpegQueue.then(job, job);
  ffmpegQueue = p.catch(() => {});
  return p;
}

// Frames arrive ONE PER REQUEST as raw PNG bytes (start -> frame x N -> finish),
// straight to disk. The old single request carried every frame as a base64 data
// URL inside one JSON string: 30-150 MB that the browser had to hold as strings
// and the server had to buffer, parse and decode, so busier posters hit the
// 120 MB server limit and failed as a bare "Export failed" (Mara, 2026-09-22).
const FRAME_JOB_TTL_MS = 15 * 60000;
const MAX_FRAMES = 600;
const frameJobs = new Map(); // job -> { dir, fmt, rate, count, size, headline, startedAt }

function badFrames(message) {
  const err = new Error(message);
  err.code = "bad_frames";
  return err;
}

function dropFrameJob(job) {
  const j = frameJobs.get(job);
  frameJobs.delete(job);
  if (j) try { fs.rmSync(j.dir, { recursive: true, force: true }); } catch { /* ignore */ }
}

export function startFrameJob({ fmt, fps, count, size, headline, draftId, nowISO }) {
  // No point uploading 144 frames the server can't encode: say so up front.
  const ff = ffmpegStatus();
  if (!ff.available) {
    const err = new Error(`ffmpeg is missing on the server, so animated exports can't run. ${ff.hint}`);
    err.code = "ffmpeg_missing";
    throw err;
  }
  // An abandoned export (tab closed mid-upload) must not strand its frames.
  const cutoff = Date.now() - FRAME_JOB_TTL_MS;
  for (const [job, j] of frameJobs) if (j.startedAt < cutoff) dropFrameJob(job);
  const n = Math.round(Number(count) || 0);
  if (n < 2 || n > MAX_FRAMES) throw badFrames(`Need between 2 and ${MAX_FRAMES} frames.`);
  const id = newId(Date.parse(nowISO) || 0);
  const dir = path.join(FILES_DIR, `seq-${id}`);
  fs.mkdirSync(dir, { recursive: true });
  frameJobs.set(id, {
    dir,
    fmt: fmt === "mp4" ? "mp4" : "gif",
    rate: Math.max(1, Math.min(60, Math.round(Number(fps) || 24))),
    count: n,
    size,
    headline,
    draftId: typeof draftId === "string" && draftId ? draftId.slice(0, 80) : null,
    startedAt: Date.now(),
  });
  return { job: id };
}

const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47]);
export function addFrame(job, index, bytes) {
  const j = frameJobs.get(job);
  if (!j) throw badFrames("This export expired or was never started. Try again.");
  const i = Number(index);
  if (!Number.isInteger(i) || i < 0 || i >= j.count) throw badFrames(`Frame ${index} is out of range.`);
  if (!Buffer.isBuffer(bytes) || bytes.length < 8 || !bytes.subarray(0, 4).equals(PNG_MAGIC)) throw badFrames(`Frame ${i} is not a PNG.`);
  fs.writeFileSync(path.join(j.dir, `f${String(i).padStart(4, "0")}.png`), bytes);
}

export async function finishFrameJob(job, nowISO) {
  const j = frameJobs.get(job);
  if (!j) throw badFrames("This export expired or was never started. Try again.");
  try {
    const have = fs.readdirSync(j.dir).filter((f) => /^f\d{4}\.png$/.test(f)).length;
    if (have !== j.count) throw badFrames(`Only ${have} of ${j.count} frames arrived. Try again.`);
    const id = job;
    const wantGif = j.fmt === "gif";
    const ff = resolveFfmpeg();
    const input = ["-y", "-framerate", String(j.rate), "-i", path.join(j.dir, "f%04d.png")];
    let outFile, mime, kind;
    if (wantGif) {
      outFile = `${id}.gif`; mime = "image/gif"; kind = "image";
      const pal = path.join(j.dir, "pal.png");
      const sc = "scale=-2:1080:flags=lanczos";
      await runFfmpeg(ff, [...input, "-vf", `${sc},palettegen=stats_mode=full:max_colors=256`, pal]);
      await runFfmpeg(ff, [...input, "-i", pal, "-lavfi", `${sc}[x];[x][1:v]paletteuse=dither=sierra2_4a:diff_mode=rectangle`, "-loop", "0", path.join(FILES_DIR, outFile)]);
    } else {
      outFile = `${id}.mp4`; mime = "video/mp4"; kind = "video";
      await runFfmpeg(ff, [...input, "-an", "-movflags", "+faststart", "-pix_fmt", "yuv420p", "-vf", "scale=trunc(iw/2)*2:trunc(ih/2)*2", "-c:v", "libx264", "-preset", "slow", "-crf", "18", "-profile:v", "high", path.join(FILES_DIR, outFile)]);
    }

    const record = {
      id, provider: "ascii-live", kind, local: true,
      file: outFile, url: `/api/images/file/${outFile}`, mime,
      size: j.size || "portrait", style: null,
      headline: j.headline || (wantGif ? "ASCII Live GIF" : "ASCII Live video"),
      subline: null, prompt: null, sourceUrl: null, draftId: j.draftId, createdAt: nowISO,
    };
    const list = load();
    list.push(record);
    persist(list);
    return record;
  } finally {
    dropFrameJob(job);
  }
}

// ---------- save a client-rendered frame ----------
// The ASCII Live tool renders its frame in the browser (three.js + canvas) and
// exports a PNG data URL. This drops those bytes straight into the same local
// image library, so a live-ASCII background lands next to the branded cards.
// Fully local — the bytes never leave the machine.
// Used by the ASCII poster (frames) and the Photo card studio (a photo with
// the headline + Larkwell logo drawn on it in the browser). `credit`/`sourceUrl`
// carry the Unsplash attribution over from the photo the card was built on.
export function saveImageBytes({ dataUrl, headline, subline, eyebrow, size, draftId, nowISO, provider, kind, style, credit, sourceUrl }) {
  const m = /^data:(image\/[a-z+]+);base64,(.+)$/i.exec(String(dataUrl || ""));
  if (!m) {
    const err = new Error("Expected a base64 image data URL.");
    err.code = "bad_data_url";
    throw err;
  }
  const mime = m[1];
  const ext = mime.includes("png") ? "png" : mime.includes("jpeg") || mime.includes("jpg") ? "jpg" : "png";
  const bytes = Buffer.from(m[2], "base64");
  const now = Date.parse(nowISO) || 0;
  const id = newId(now);

  if (!fs.existsSync(FILES_DIR)) fs.mkdirSync(FILES_DIR, { recursive: true });
  const file = `${id}.${ext}`;
  fs.writeFileSync(path.join(FILES_DIR, file), bytes);

  const str = (v, n) => (typeof v === "string" && v ? v.slice(0, n) : null);
  const record = {
    id,
    provider: str(provider, 40) || "ascii-live",
    kind: str(kind, 20) || "card",
    local: true,
    file,
    url: `/api/images/file/${file}`,
    mime,
    size: size || "portrait",
    style: str(style, 40),
    headline: str(headline, 200) || "ASCII Live frame",
    subline: str(subline, 300),
    eyebrow: str(eyebrow, 80), // photo cards: the small label above the headline
    prompt: null,
    sourceUrl: str(sourceUrl, 500),
    credit: str(credit, 200),
    draftId: typeof draftId === "string" && draftId ? draftId.slice(0, 80) : null,
    createdAt: nowISO,
  };
  const list = load();
  list.push(record);
  persist(list);
  return record;
}
