// The Larkwell wing mark (public/brand/mark.svg, an invented logo drawn for
// this template, 360x219). Lives in public/brand/ so the browser can load
// it too (the Photo card studio draws it on a canvas) and Vite ships it in
// dist/. Embedded here as a data URI so the SVG stays a
// single self-contained file: browsers allow data: images inside an SVG that
// is loaded via <img>, and the client's SVG -> PNG download keeps working.
// Two variants: full colour for the light style, a white knockout for the
// dark styles (the navy in the colour mark disappears against brand blue).
// Mara's bug (2026-09-23): the footer drew a plain blue circle where the
// logo should be.
function loadMark(file) {
  try {
    return `data:image/svg+xml;base64,${fs.readFileSync(path.join(__dirname, "../public/brand", file)).toString("base64")}`;
  } catch {
    return "";
  }
}
const MARK = { colour: loadMark("mark.svg"), white: loadMark("mark-white.svg") };
const MARK_RATIO = 360 / 219; // width / height of the marks above

function esc(s) {
  return String(s || "").replace(/[<>&'"]/g, (c) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", "'": "&apos;", '"': "&quot;" }[c]));
}

// Greedy word-wrap by an estimated glyph width (Inter Tight ~0.52em average).
function wrapText(text, fontSize, maxWidth, maxLines) {
  const words = String(text || "").trim().split(/\s+/).filter(Boolean);
  const perChar = fontSize * 0.52;
  const maxChars = Math.max(6, Math.floor(maxWidth / perChar));
  const lines = [];
  let line = "";
  for (const w of words) {
    const candidate = line ? `${line} ${w}` : w;
    if (candidate.length > maxChars && line) {
      lines.push(line);
      line = w;
    } else {
      line = candidate;
    }
    if (lines.length === maxLines - 1 && line.length > maxChars) break;
  }
  if (line) lines.push(line);
  if (lines.length > maxLines) {
    const kept = lines.slice(0, maxLines);
    kept[maxLines - 1] = kept[maxLines - 1].replace(/[.,;:]?$/, "…");
    return kept;
  }
  return lines;
}

function renderCardSVG({ headline, subline, style, size }) {
  const { w, h } = sizeOf(size);
  const st = CARD_STYLES[style] || CARD_STYLES.brand;
  const pad = Math.round(w * 0.075);
  const fontStack = `'Inter Tight','Inter',ui-sans-serif,system-ui,-apple-system,Segoe UI,Roboto,Arial,sans-serif`;

  // Headline scales with canvas; wrap to the content width.
  const hSize = Math.round(Math.min(w, h) * (size === "linkedin" ? 0.072 : 0.082));
  const contentW = w - pad * 2;
  const hLines = wrapText(headline || company.name, hSize, contentW, 4);
  const lineH = Math.round(hSize * 1.12);

  // Background (solid or gradient) + optional tech grid.
  let defs = "";
  let bgFill = st.bg;
  if (typeof st.bg === "string" && st.bg.startsWith("grad:")) {
    const [, c1, c2] = st.bg.split(":");
    defs += `<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${c1}"/><stop offset="1" stop-color="${c2}"/></linearGradient>`;
    bgFill = "url(#bg)";
  }
  let grid = "";
  if (st.grid) {
    defs += `<pattern id="grid" width="48" height="48" patternUnits="userSpaceOnUse"><path d="M48 0H0V48" fill="none" stroke="${BRAND_BRIGHT}" stroke-opacity="0.08" stroke-width="1"/></pattern>`;
    grid = `<rect width="${w}" height="${h}" fill="url(#grid)"/><circle cx="${w * 0.82}" cy="${h * 0.2}" r="${w * 0.28}" fill="${BRAND}" opacity="0.18"/>`;
  }

  // Headline block, vertically centred-ish in the upper-middle.
  const blockH = hLines.length * lineH;
  let y = Math.round(h * 0.5 - blockH * 0.5);
  const headlineSVG = hLines
    .map((ln, i) => `<text x="${pad}" y="${y + i * lineH}" font-family="${fontStack}" font-size="${hSize}" font-weight="700" fill="${st.ink}" letter-spacing="-0.5">${esc(ln)}</text>`)
    .join("");

  // Accent rule above the headline.
  // (y is the first line's baseline: clear the capitals, then leave a gap.)
  const ruleY = y - Math.round(hSize * 1.3);
  const rule = `<rect x="${pad}" y="${ruleY}" width="${Math.round(w * 0.09)}" height="6" rx="3" fill="${st.accent}"/>`;

  // Subline under the headline (optional).
  let sub = "";
  if (subline) {
    const sSize = Math.round(hSize * 0.4);
    const sLines = wrapText(subline, sSize, contentW, 2);
    const sy = y + blockH + Math.round(sSize * 1.2);
    sub = sLines.map((ln, i) => `<text x="${pad}" y="${sy + i * Math.round(sSize * 1.3)}" font-family="${fontStack}" font-size="${sSize}" font-weight="500" fill="${st.sub}">${esc(ln)}</text>`).join("");
  }

  // Footer: the Larkwell wing mark + wordmark. The mark is roughly twice the
  // wordmark's cap height so it reads as a logo, not an icon.
  const markY = h - pad;
  const markSize = Math.round(hSize * 0.42);
  const markH = Math.round(markSize * 2.2);
  const markW = Math.round(markH * MARK_RATIO);
  const markSrc = st.mark === "colour" ? MARK.colour : MARK.white;
  // Bottom of the mark sits on the wordmark's baseline (the cloud's flat base
  // aligns with the text), nudged down a touch for optical balance.
  const dot = markSrc
    ? `<image href="${markSrc}" x="${pad}" y="${markY - markH + Math.round(markSize * 0.12)}" width="${markW}" height="${markH}" preserveAspectRatio="xMinYMax meet"/>`
    : `<circle cx="${pad + markSize * 0.45}" cy="${markY - markSize * 0.35}" r="${markSize * 0.45}" fill="${st.accent}"/>`;
  const textX = pad + (markSrc ? markW + Math.round(markSize * 0.45) : Math.round(markSize * 1.25));
  const wordmark = `<text x="${textX}" y="${markY}" font-family="${fontStack}" font-size="${markSize}" font-weight="700" letter-spacing="0" fill="${st.ink}">${esc(company.shortName.toLowerCase())}</text>`;

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
<defs>${defs}</defs>
<rect width="${w}" height="${h}" fill="${bgFill}"/>
${grid}
${rule}
${headlineSVG}
${sub}
${dot}${wordmark}
</svg>`;
}

