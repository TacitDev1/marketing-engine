// ---------- store ----------

let _counter = 0;
function newId(now) {
  return `img-${now}-${_counter++}`;
}

function load() {
  try {
    return JSON.parse(fs.readFileSync(STORE, "utf8"));
  } catch {
    return [];
  }
}

function persist(list) {
  writeJsonAtomic(STORE, list);
}

// Newest first.
export function listImages() {
  return load().sort((a, b) => (b.createdAt || "").localeCompare(a.createdAt || ""));
}

export function deleteImage(id) {
  const list = load();
  const rec = list.find((x) => x.id === id);
  if (rec?.file) {
    try {
      fs.unlinkSync(path.join(FILES_DIR, rec.file));
    } catch {
      /* file may already be gone */
    }
  }
  const next = list.filter((x) => x.id !== id);
  persist(next);
  return next.length !== list.length;
}

// Stream a saved image file by name (path-traversal guarded — basename only).
export function imageFilePath(name) {
  const safe = path.basename(String(name || ""));
  const full = path.join(FILES_DIR, safe);
  return fs.existsSync(full) ? full : null;
}

