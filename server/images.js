// Unsplash search wants keywords, not a diffusion prompt. Squeeze the image
// direction ("Professional, modern enterprise technology scene, corporate blue
// palette, no text...") down to the words that describe the actual subject.
const UNSPLASH_FILLER = new Set([
  "a", "an", "the", "of", "in", "on", "with", "and", "or", "for", "to", "no", "not",
  "professional", "photography", "photographic", "photo", "image", "illustration",
  "scene", "depicting", "showing", "showcasing", "representing", "featuring",
  "modern", "clean", "composition", "corporate", "blue", "palette", "aesthetic",
  "style", "high", "detail", "detailed", "sharp", "focus", "vivid", "cinematic",
  "text", "logo", "logos", "watermark", "watermarks", "quality", "realistic",
]);
function unsplashQuery(prompt) {
  const words = String(prompt || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !UNSPLASH_FILLER.has(w));
  return words.slice(0, 6).join(" ") || "enterprise technology";
}

async function unsplashSearch({ key, query, orientation, page }) {
  const q = new URLSearchParams({ query, orientation, page: String(page), per_page: "30", content_filter: "high" });
  const res = await fetchTimeout(`https://api.unsplash.com/search/photos?${q}`, {
    headers: { Authorization: `Client-ID ${key}`, "Accept-Version": "v1" },
  }, 30000);
  if (res.status === 401 || res.status === 403) {
    throw new Error("Unsplash rejected the key. Check UNSPLASH_ACCESS_KEY in .env (a free key from unsplash.com/developers).");
  }
  if (!res.ok) throw new Error(`Unsplash returned ${res.status}`);
  return (await res.json())?.results || [];
}

async function unsplashFetch({ prompt, size }) {
  const key = process.env.UNSPLASH_ACCESS_KEY;
  const { w, h } = sizeOf(size);
  const orientation = w === h ? "squarish" : w > h ? "landscape" : "portrait";
  const query = unsplashQuery(prompt);

  // Never serve a photo the library already holds: the same keyword must give a
  // FRESH image every time. Used ids come from the saved records (so deleting
  // an image frees it up again); if page 1's 30 are all used, dig into page 2,
  // and only ever repeat when a keyword is genuinely exhausted.
  const usedIds = new Set(load().map((r) => r.unsplashId).filter(Boolean));
  let results = [];
  let fresh = [];
  for (let page = 1; page <= 3 && !fresh.length; page++) {
    results = await unsplashSearch({ key, query, orientation, page });
    if (!results.length) break; // no more pages
    fresh = results.filter((p) => !usedIds.has(p.id));
  }
  if (!fresh.length && !results.length) throw new Error(`Unsplash found no photos for "${query}". Try a simpler prompt.`);
  const pool = fresh.length ? fresh : results; // exhausted keyword -> honest repeat
  const photo = pool[Math.floor(Math.random() * Math.min(pool.length, 10))];

  const imgUrl = `${photo.urls.raw}&w=${w}&h=${h}&fit=crop&crop=entropy&q=85&fm=jpg`;
  const img = await fetchTimeout(imgUrl, {}, 60000);
  if (!img.ok) throw new Error(`Unsplash image fetch returned ${img.status}`);
  const bytes = Buffer.from(await img.arrayBuffer());

  // Unsplash API guideline: report a download when the photo is actually used.
  const dl = photo.links?.download_location;
  if (dl) fetchTimeout(`${dl}${dl.includes("?") ? "&" : "?"}client_id=${key}`, {}, 15000).catch(() => {});

  // Attribution per their guideline: credit the photographer, link with UTM
  // tags. (This provider is only ever human-initiated from the Images screen —
  // never wire it into the Worker/autopilot: the API is for non-automated use.)
  const utm = "utm_source=marketing-engine&utm_medium=referral";
  const profile = photo.user?.links?.html;
  return {
    bytes,
    ext: "jpg",
    mime: "image/jpeg",
    sourceUrl: profile ? `${profile}?${utm}` : `${photo.links?.html || "https://unsplash.com"}?${utm}`,
    credit: photo.user?.name ? `Photo by ${photo.user.name} on Unsplash` : "Unsplash",
    unsplashId: photo.id, // remembered so this photo is never picked again
  };
}

